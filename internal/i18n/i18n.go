package i18n

import (
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"strings"
	"sync/atomic"
)

var language atomic.Value

func Set(lang string) { language.Store(normalize(lang)) }

func Lang() string {
	if lang, ok := language.Load().(string); ok {
		return lang
	}
	return "en"
}

func T(src string, args ...any) string {
	text := src
	if translated := catalog[src][Lang()]; translated != "" {
		text = translated
	}
	if len(args) > 0 {
		return fmt.Sprintf(text, args...)
	}
	return text
}

func normalize(lang string) string {
	lang = strings.ToLower(strings.TrimSpace(lang))
	if len(lang) >= 2 {
		lang = lang[:2]
	}
	switch lang {
	case "en", "pt", "es", "fr", "de", "it", "ja", "zh":
		return lang
	}
	return "en"
}

func Detect(configValue string) string {
	if lang := os.Getenv("TARS_LANG"); lang != "" {
		return normalize(lang)
	}
	if configValue != "" && configValue != "auto" {
		return normalize(configValue)
	}
	if runtime.GOOS == "darwin" {
		if out, err := exec.Command("defaults", "read", "-g", "AppleLanguages").Output(); err == nil {
			first := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(string(out)), "("))
			first = strings.TrimSpace(strings.SplitN(first, ",", 2)[0])
			first = strings.Trim(first, "\" \t\r\n)")
			if first != "" {
				return normalize(first)
			}
		}
	}
	for _, key := range []string{"LC_ALL", "LC_MESSAGES", "LANG"} {
		if lang := os.Getenv(key); lang != "" {
			return normalize(lang)
		}
	}
	return "en"
}

func LanguageName() string {
	switch Lang() {
	case "pt":
		return "Brazilian Portuguese"
	case "es":
		return "Spanish"
	case "fr":
		return "French"
	case "de":
		return "German"
	case "it":
		return "Italian"
	case "ja":
		return "Japanese"
	case "zh":
		return "Simplified Chinese"
	}
	return "English"
}

func Decimal() string {
	switch Lang() {
	case "pt", "es", "fr", "de", "it":
		return ","
	}
	return "."
}

